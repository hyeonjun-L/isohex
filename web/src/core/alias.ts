let IDX: Map<string, string[]> | null = null
let WORDS: string[] = []

function index(): Map<string, string[]> {
  if (IDX) return IDX
  const m = new Map<string, string[]>()
  for (const [codes, words] of ROWS) {
    const cs = codes.split(' ')
    for (const w of words.split(' ')) {
      const a = m.get(w) ?? []
      for (const c of cs) if (!a.includes(c)) a.push(c)
      m.set(w, a)
    }
  }
  IDX = m
  // 긴 낱말 먼저 — '들어 있는 낱말'을 찾을 때 '수제버거'가 '버거'보다 먼저 걸리게
  WORDS = [...m.keys()].sort((a, b) => b.length - a.length || (a < b ? -1 : 1))
  return m
}

export interface AliasHit {
  /** 사전의 낱말 */
  w: string
  codes: readonly string[]
}

/** 찾는 말 다듬기 — 빈칸을 없애고 소문자로 */
export function normQ(q: string): string {
  return q.replace(/\s/g, '').toLowerCase()
}

/** 낱말과 똑같은 별칭의 코드 (없으면 빈 목록) — s는 normQ를 거친 것 */
export function aliasExact(s: string): readonly string[] {
  return index().get(s) ?? []
}

/** s로 시작하는 별칭들 — 짧은 낱말 먼저 (치는 중인 말: '삼겹' → '삼겹살') */
export function aliasPrefix(s: string): AliasHit[] {
  const out: AliasHit[] = []
  if (!s) return out
  for (const [w, codes] of index()) if (w.length > s.length && w.startsWith(s)) out.push({ w, codes })
  return out.sort((a, b) => a.w.length - b.w.length || (a.w < b.w ? -1 : 1))
}

/** s 안에 든 가장 긴 별칭(두 글자 이상) — '동네빵집' → '빵집' */
export function aliasInside(s: string): AliasHit | null {
  const m = index()
  for (const w of WORDS) if (w.length >= 2 && w.length < s.length && s.includes(w)) return { w, codes: m.get(w)! }
  return null
}

/** 사전에 있는 낱말 모두 (시험 · 점검용) */
export function aliasWords(): string[] {
  index()
  return [...WORDS]
}

/** 사전에 적힌 코드 모두 (시험 · 점검용 — 업종 목록에 없는 코드가 섞이지 않았는지) */
export function aliasCodes(): string[] {
  return [...new Set(ROWS.flatMap(([codes]) => codes.split(' ')))]
}
